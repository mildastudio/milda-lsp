// Generates the highlight parity artifacts from the TS source of truth:
//   1. Golden token streams for each corpus file (highlight-corpus/*.tokens.json) -
//      the contract the Kotlin lexer must match.
//   2. MildaVocab.kt - the shared keyword/type/color-fn sets, code-generated into the
//      JetBrains plugin so the Kotlin lexer can't drift from ./src/vocab.ts.
//   3. milda.tmLanguage.json - the TextMate grammar, built from the same vocab so its
//      word lists can't drift either. Written to BOTH consumers: the VS Code / Open VSX
//      extension (packages/milda-vscode) and the plugin-free JetBrains TextMate bundle
//      (docs/dsl/editors/jetbrains), which also gets a copy of the extension's
//      language-configuration.json. Either destination is skipped when it isn't checked
//      out - the standalone milda-lsp mirror has neither.
// Run: npm run gen:highlight -w @mildastudio/milda-lsp

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { computeSemanticTokens, decodeSemanticTokens } from '../src/semantic-tokens'
import { buildTmLanguage } from '../src/tmgrammar'
import { COLOR_FNS, DECLARATION_KEYWORDS, KEYWORDS, LENGTH_FNS, TYPE_WORDS } from '../src/vocab'

const here = dirname(fileURLToPath(import.meta.url))
const corpusDir = join(here, '..', 'highlight-corpus')

const corpus = readdirSync(corpusDir)
  .filter((f) => f.endsWith('.milda'))
  .sort()
for (const f of corpus) {
  const text = readFileSync(join(corpusDir, f), 'utf8')
  const tokens = decodeSemanticTokens(computeSemanticTokens(text).data)
  writeFileSync(
    join(corpusDir, f.replace(/\.milda$/, '.tokens.json')),
    `${JSON.stringify(tokens, null, 2)}\n`,
  )
}

const set = (name: string, list: readonly string[]) =>
  `    val ${name}: Set<String> = setOf(\n${list.map((w) => `        ${JSON.stringify(w)}`).join(',\n')},\n    )`
const kotlin = `// GENERATED by packages/milda-lsp/tools/gen-highlight.ts - DO NOT EDIT BY HAND.
// Source of truth: packages/milda-lsp/src/vocab.ts (run \`npm run gen:highlight\`).
package studio.milda.lang

object MildaVocab {
${set('KEYWORDS', KEYWORDS)}

${set('TYPE_WORDS', TYPE_WORDS)}

${set('COLOR_FNS', COLOR_FNS)}

${set('LENGTH_FNS', LENGTH_FNS)}

${set('DECLARATION_KEYWORDS', DECLARATION_KEYWORDS)}
}
`
const ktDir = join(
  here,
  '..',
  '..',
  'milda-jetbrains',
  'src',
  'main',
  'kotlin',
  'studio',
  'milda',
  'lang',
)
mkdirSync(ktDir, { recursive: true })
writeFileSync(join(ktDir, 'MildaVocab.kt'), kotlin)

// TextMate grammar - one build, written to every consumer that is checked out.
const grammar = `${JSON.stringify(buildTmLanguage(), null, 2)}\n`
const vscodeDir = join(here, '..', '..', 'milda-vscode')
const bundleDir = join(here, '..', '..', '..', 'docs', 'dsl', 'editors', 'jetbrains')
const wrote: string[] = []

if (existsSync(vscodeDir)) {
  mkdirSync(join(vscodeDir, 'syntaxes'), { recursive: true })
  writeFileSync(join(vscodeDir, 'syntaxes', 'milda.tmLanguage.json'), grammar)
  wrote.push('milda-vscode')
}

// The JetBrains TextMate bundle is a flat folder (grammar + language config + manifest
// side by side), and its editing behaviour should match the extension's, so the
// hand-written language-configuration.json is copied rather than maintained twice.
if (existsSync(bundleDir)) {
  writeFileSync(join(bundleDir, 'milda.tmLanguage.json'), grammar)
  if (existsSync(vscodeDir)) {
    writeFileSync(
      join(bundleDir, 'language-configuration.json'),
      readFileSync(join(vscodeDir, 'language-configuration.json'), 'utf8'),
    )
  }
  wrote.push('textmate bundle')
}

console.log(
  `generated ${corpus.length} golden token file(s) + MildaVocab.kt` +
    `${wrote.length ? ` + milda.tmLanguage.json (${wrote.join(', ')})` : ''}`,
)
