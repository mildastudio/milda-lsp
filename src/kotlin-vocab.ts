// ─── The vocabulary, printed as Kotlin ────────────────────────────────────────
// The JetBrains plugin's lexer cannot import ./vocab, so `gen:highlight` prints the same sets as
// a Kotlin object (MildaVocab.kt). The printing lives here rather than in the tool so a test can
// compare the committed file with what the tool would write today: the grammar had that check,
// and the Kotlin copy - the one whose own tests only run under Gradle, outside CI - did not.

import { COLOR_FNS, DECLARATION_KEYWORDS, KEYWORDS, LENGTH_FNS, TYPE_WORDS } from './vocab'

const set = (name: string, list: readonly string[]) =>
  `    val ${name}: Set<String> = setOf(\n${list.map((w) => `        ${JSON.stringify(w)}`).join(',\n')},\n    )`

export function buildKotlinVocab(): string {
  return `// GENERATED by packages/milda-lsp/tools/gen-highlight.ts - DO NOT EDIT BY HAND.
// Source of truth: packages/milda-lsp/src/vocab.ts (run \`npm run gen:highlight\`).
package studio.milda.lang

object MildaVocab {
${set('KEYWORDS', KEYWORDS)}

${set('TYPE_WORDS', TYPE_WORDS)}

${set('COLOR_FNS', COLOR_FNS)}

${set('LENGTH_FNS', LENGTH_FNS)}

${set('DECLARATION_KEYWORDS', DECLARATION_KEYWORDS)}
}
`
}
